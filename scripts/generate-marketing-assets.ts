async function main() {
  if (!TOKEN) throw new Error("REPLICATE_API_TOKEN is not set");
  await mkdir(OUT, { recursive: true });

  const only = process.argv[2];
  const manifest: Record<string, string> = {};

  if (!only || only === "hero") await runHero();
  if (!only || only === "auth") await runAuth();
  if (!only || only === "images") {
    Object.assign(
      manifest,
      await runImages([...GALLERY, ...TEMPLATES, ...SHOWCASE, ...FEATURES]),
    );
  }

  if (Object.keys(manifest).length > 0) {
    // Written so the page can state what produced each tile. An AI product
    // showing generated work without the prompt is asking to be doubted.
    await writeFile(
      path.join(OUT, "prompts.json"),
      JSON.stringify(manifest, null, 2) + "\n",
      "utf8",
    );
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
