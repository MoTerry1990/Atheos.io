const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/**
 * Replicate throttles hard when the account balance is low — six predictions a
 * minute, burst of one, below $5 of credit. That is not an error condition, it
 * is the documented behaviour, so it is retried rather than reported. The API
 * returns `retry_after` in seconds; a second of slack on top covers clock skew
 * between us and them.
 */
async function submit(version: string, input: Record<string, unknown>) {
  for (let attempt = 0; attempt < 8; attempt += 1) {
    const response = await fetch("https://api.replicate.com/v1/predictions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${TOKEN}`,
        "Content-Type": "application/json",
        Prefer: "wait=60",
      },
      body: JSON.stringify({ version, input }),
    });

    if (response.status !== 429) return response;

    const body = (await response.json()) as { retry_after?: number };
    await sleep(((body.retry_after ?? 10) + 1) * 1000);
  }
  throw new Error("still throttled after 8 attempts");
}

async function replicate(version: string, input: Record<string, unknown>) {
  const start = await submit(version, input);

  if (!start.ok) {
    throw new Error(`${start.status} ${await start.text()}`);
  }

  let prediction = (await start.json()) as {
    id: string;
    status: string;
    output?: unknown;
    error?: string;
    urls: { get: string };
  };

  // `Prefer: wait` returns early for anything slower than a minute, which is
  // every video and some images. Poll from there.
  while (["starting", "processing"].includes(prediction.status)) {
    await sleep(3000);
    const poll = await fetch(prediction.urls.get, {
      headers: { Authorization: `Bearer ${TOKEN}` },
    });
    prediction = await poll.json();
  }

  if (prediction.status !== "succeeded") {
    throw new Error(`${prediction.status}: ${prediction.error ?? "no output"}`);
  }

  const output = prediction.output;
  const url = Array.isArray(output) ? output[0] : output;
  if (typeof url !== "string") {
    throw new Error(`unexpected output shape: ${JSON.stringify(output)}`);
  }
  return url;
}

async function download(url: string, file: string) {
  const response = await fetch(url);
  if (!response.ok || !response.body) {
    throw new Error(`download failed: ${response.status}`);
  }
  await pipeline(
    Readable.fromWeb(response.body as never),
    createWriteStream(file),
  );
}

async function runImages(jobs: ImageJob[]) {
  const manifest: Record<string, string> = {};

  for (const job of jobs) {
    const file = path.join(OUT, `${job.name}.webp`);

    // Already on disk. These are committed assets, so a re-run after a
    // throttled batch should fill the gaps rather than pay for the whole set
    // again — and rerunning must not silently redecorate tiles that are fine.
    if (existsSync(file)) {
      manifest[job.name] = job.prompt;
      console.log(`${job.name} … cached`);
      continue;
    }

    process.stdout.write(`${job.name} … `);
    try {
      const url = await replicate(FLUX_SCHNELL, {
        prompt: `${job.prompt}. ${HOUSE}`,
        aspect_ratio: job.aspect,
        output_format: "webp",
        // 90 rather than the default 80: these are hero-adjacent and the extra
        // few kilobytes are cheaper than visible banding on a dark gradient.
        output_quality: 90,
        num_outputs: 1,
        seed: job.seed,
      });
      await download(url, file);
      manifest[job.name] = job.prompt;
      console.log("ok");
    } catch (error) {
      console.log(`FAILED — ${error instanceof Error ? error.message : error}`);
    }
  }

  return manifest;
}

