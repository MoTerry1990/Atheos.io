/**
 * Generate the marketing site's imagery with the product's own models.
 *
 *   npx dotenv-cli -e .env.local -- npx tsx scripts/generate-marketing-assets.ts
 *   npx dotenv-cli -e .env.local -- npx tsx scripts/generate-marketing-assets.ts hero
 *
 * ## Why generate rather than buy stock
 *
 * Atheos sells image and video generation. A landing page for it decorated
 * with Pexels footage is making a claim it is simultaneously disproving, and
 * the first visitor who reverse-image-searches the hero finds that out. Every
 * asset here comes from the **same pinned model versions the product runs** —
 * so the page is a demo, not a mock-up, and the caption under a gallery tile
 * is literally the prompt that produced it.
 *
 * ## Cost
 *
 * Real money, on the live Replicate account. At measured rates an image is
 * about $0.003 and five seconds of 720p video about $0.10, so a full run is
 * well under a dollar. Outputs are committed to `public/marketing/`, so this
 * script runs when the imagery should change and never on a build.
 *
 * ## WebM is encoded by hand, afterwards
 *
 * Replicate returns H.264 only. The site serves a VP9/WebM alternate first —
 * 720 KB against 1,310 KB for the hero — so after regenerating a video, run:
 *
 *   ffmpeg -i public/marketing/hero.mp4 -c:v libvpx-vp9 -crf 34 -b:v 0  *     -row-mt 1 -an public/marketing/hero.webm
 *
 * Skipping it is not fatal: the browser falls through to the MP4 `<source>`.
 * It just costs every non-Safari visitor an extra 590 KB.
 *
 * ## Determinism
 *
 * Every request carries an explicit seed. Re-running reproduces the same
 * images rather than quietly redecorating the site, and a single tile can be
 * regenerated by changing one seed.
 */

